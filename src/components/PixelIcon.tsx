export type IconName = keyof typeof ICONS;

export default function PixelIcon({
  name,
  color = "currentColor",
  light = "#fff",
  size = 16,
}: {
  name: IconName;
  color?: string;
  light?: string;
  size?: number;
}) {
  const rows = ICONS[name];
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true">
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === "+" ? light : color} />,
        ),
      )}
    </svg>
  );
}
